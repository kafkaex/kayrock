defmodule Kayrock.Integration.TaggedFieldsTest do
  @moduledoc """
  Named tagged fields (KIP-482) against a real Apache Kafka 4.4.0 broker.

  ApiVersions v4 is not generated by Kayrock yet (the API table is capped at
  v3), so its modules are generated from the vendored 4.4.0 JSON specs into a
  test namespace, as in `Kayrock.Generate.TaggedFieldsTest`.  The broker sends
  SupportedFeatures (tag 0), FinalizedFeaturesEpoch (tag 1) and
  FinalizedFeatures (tag 2) in the response's tagged-field section.
  """
  use Kayrock.IntegrationCase
  use ExUnit.Case, async: false

  alias Kayrock.Generate.ApiTable
  alias Kayrock.Generate.JsonSpec
  alias Kayrock.Test.GeneratedCode

  defmodule KafkaSchema do
    @moduledoc false
    alias Kayrock.Generate.ApiTable
    alias Kayrock.Generate.JsonSpec

    defp spec, do: JsonSpec.load!(ApiTable.spec_dir())

    def vsn_range(api) do
      {min, _} = JsonSpec.valid_versions(spec(), api)
      {min, JsonSpec.max_stable_version(spec(), api)}
    end

    def min_flexible_vsn(api), do: JsonSpec.min_flexible_version(spec(), api) || 9999
    def api_key(api), do: JsonSpec.api_key(spec(), api)
    def req(api, vsn), do: JsonSpec.request_schema(spec(), api, vsn)
    def rsp(api, vsn), do: JsonSpec.response_schema(spec(), api, vsn)
    def request_header_vsn(api, vsn), do: JsonSpec.request_header_version(spec(), api, vsn)
    def response_header_vsn(api, vsn), do: JsonSpec.response_header_version(spec(), api, vsn)
  end

  @namespace Kayrock.Integration.TaggedFieldsTest.Gen
  @image "apache/kafka:4.4.0"
  @port 9092

  container(
    :kafka,
    @image
    |> Container.new()
    |> Container.with_exposed_port(@port)
    |> Container.with_waiting_strategy(
      Testcontainers.LogWaitStrategy.new(~r/Kafka Server started/, 120_000)
    ),
    shared: true
  )

  setup_all do
    GeneratedCode.compile!(:api_versions, KafkaSchema, @namespace)
    :ok
  end

  defp call(kafka, %module{} = request) do
    {:ok, conn} =
      Kayrock.BrokerConnection.start_link("localhost", Container.mapped_port(kafka, @port), [])

    on_exit(fn -> if Process.alive?(conn), do: GenServer.stop(conn) end)

    wire = module.serialize(%{request | correlation_id: 42, client_id: "kayrock-test"})

    :ok = Kayrock.BrokerConnection.send(conn, wire)
    {:ok, resp} = Kayrock.BrokerConnection.recv(conn)
    {response, <<>>} = module.response_deserializer().(resp)
    response
  end

  test "ApiVersions v4 decodes the broker's tagged fields into named fields", %{kafka: kafka} do
    assert JsonSpec.max_stable_version(JsonSpec.load!(ApiTable.spec_dir()), :api_versions) >= 4

    request =
      struct(GeneratedCode.module(@namespace, :api_versions, 4, Request),
        client_software_name: "kayrock",
        client_software_version: "test"
      )

    response = call(kafka, request)

    assert response.correlation_id == 42
    assert response.error_code == 0
    assert Enum.any?(response.api_keys, &(&1.api_key == 18))

    # a KRaft broker always reports its supported features and an epoch
    assert is_list(response.supported_features)
    feature_names = Enum.map(response.supported_features, & &1.name)
    assert "metadata.version" in feature_names
    assert Enum.all?(response.supported_features, &(&1.max_version >= &1.min_version))

    assert is_integer(response.finalized_features_epoch)
    assert response.finalized_features_epoch >= 0

    finalized = Map.new(response.finalized_features, &{&1.name, &1})
    assert %{max_version_level: level} = finalized["metadata.version"]
    assert level > 0

    # all three are known tags, so nothing is left in the raw bucket
    assert response.tagged_fields == []
  end
end
