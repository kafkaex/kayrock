defmodule Kayrock.Generate do
  @moduledoc """
  Macros for generating modules for the protocol schema
  """

  require Kayrock.Serialize
  require Kayrock.Deserialize

  def generate_schema_metadata(schema_module) do
    all_apis = schema_module.all_apis()

    version_ranges =
      Enum.map(all_apis, fn api ->
        quote do
          def version_range(unquote(api)), do: unquote(schema_module.vsn_range(api))
        end
      end)

    api_keys =
      List.flatten(
        Enum.map(all_apis, fn api ->
          key = schema_module.api_key(api)

          quote do
            def api_key(unquote(api)), do: unquote(key)
            def api_key(unquote(key)), do: unquote(api)
          end
        end)
      )

    request_schemas =
      List.flatten(
        Enum.map(all_apis, fn api ->
          {min_vsn, max_vsn} = schema_module.vsn_range(api)

          Enum.map(min_vsn..max_vsn, fn vsn ->
            quote do
              def request_schema(unquote(api), unquote(vsn)) do
                unquote(schema_module.req(api, vsn))
              end
            end
          end)
        end)
      )

    response_schemas =
      List.flatten(
        Enum.map(all_apis, fn api ->
          {min_vsn, max_vsn} = schema_module.vsn_range(api)

          Enum.map(min_vsn..max_vsn, fn vsn ->
            quote do
              def response_schema(unquote(api), unquote(vsn)) do
                unquote(schema_module.rsp(api, vsn))
              end
            end
          end)
        end)
      )

    min_known_error_code = -1
    max_known_error_code = 71

    error_codes =
      Enum.map(min_known_error_code..max_known_error_code, fn error_code ->
        error = schema_module.ec(error_code)

        quote do
          def error_code_to_error(unquote(error_code)) do
            unquote(error)
          end
        end
      end)

    quote do
      defmodule Kayrock.KafkaSchemaMetadata do
        @moduledoc false
        _ = "THIS CODE IS GENERATED BY KAYROCK"

        def all_apis do
          unquote(all_apis)
        end

        unquote_splicing(version_ranges)

        unquote_splicing(api_keys)

        unquote_splicing(request_schemas)

        unquote_splicing(response_schemas)

        def min_known_error_code, do: unquote(min_known_error_code)
        def max_known_error_code, do: unquote(max_known_error_code)

        unquote_splicing(error_codes)
      end
    end
  end

  def build_all(api, schema_module) do
    modname = Module.concat([Kayrock, Macro.camelize("#{api}")])
    contents = build_modules(api, schema_module, modname)

    quote do
      defmodule unquote(modname) do
        @api unquote(api)
        @moduledoc """
        Kayrock-generated module for the Kafka `#{@api}` API
        """
        _ = " THIS CODE IS GENERATED BY KAYROCK"
        unquote_splicing(contents)
      end
    end
  end

  # Helper to check if a version uses flexible format (KIP-482)
  defp flexible_version?(api, vsn, schema_module) do
    min_flexible = schema_module.min_flexible_vsn(api)
    vsn >= min_flexible
  catch
    # If the API doesn't have flexible versions, it will throw
    :error, _ -> false
  end

  # Request header version (RequestHeader.json): v2 for flexible versions,
  # v1 otherwise.  Schema modules may override this via request_header_vsn/2
  # (`Kayrock.Generate.SchemaSource` does, from the JSON specs).
  defp request_header_version(api, vsn, schema_module) do
    if exports?(schema_module, :request_header_vsn, 2) do
      schema_module.request_header_vsn(api, vsn)
    else
      if flexible_version?(api, vsn, schema_module), do: 2, else: 1
    end
  end

  defp exports?(module, fun, arity) do
    Code.ensure_loaded?(module) and function_exported?(module, fun, arity)
  end

  # Response header version (ResponseHeader.json): v1 for flexible versions,
  # v0 otherwise, except ApiVersions which always uses v0 (KIP-511).
  defp response_header_version(api, vsn, schema_module) do
    cond do
      exports?(schema_module, :response_header_vsn, 2) ->
        schema_module.response_header_vsn(api, vsn)

      api == :api_versions ->
        0

      flexible_version?(api, vsn, schema_module) ->
        1

      true ->
        0
    end
  end

  def build_modules(api, schema_module, modname) do
    {vmin, vmax} = schema_module.vsn_range(api)

    List.flatten(
      [
        quote do
          @vmin unquote(vmin)
          @vmax unquote(vmax)
        end
      ] ++
        Enum.map(vmin..vmax, &make_request_module(api, &1, schema_module)) ++
        [
          quote do
            @doc "Returns a request struct for this API with the given version"
            @spec get_request_struct(integer) :: request_t
          end
        ] ++
        Enum.map(vmin..vmax, &make_request_getter(&1)) ++
        Enum.map(vmin..vmax, &make_response_module(api, &1, schema_module)) ++
        [
          quote do
            @doc "Deserializes raw wire data for this API with the given version"
            @spec deserialize(integer, binary) :: {response_t, binary}
          end
        ] ++
        Enum.map(vmin..vmax, &make_response_deserializer(&1)) ++
        make_types(modname, vmin, vmax) ++
        [
          quote do
            @doc "Returns the minimum version of this API supported by Kayrock (#{@vmin})"
            @spec min_vsn :: integer
            def min_vsn, do: unquote(vmin)
          end,
          quote do
            @doc "Returns the maximum version of this API supported by Kayrock (#{@vmax})"
            @spec max_vsn :: integer
            def max_vsn, do: unquote(vmax)
          end
        ]
    )
  end

  def make_types(root_module, vmin, vmax) do
    request_ts =
      for v <- vmin..vmax do
        quote do
          unquote(Module.concat([root_module, "V#{v}", Request])).t()
        end
      end

    response_ts =
      for v <- vmin..vmax do
        quote do
          unquote(Module.concat([root_module, "V#{v}", Response])).t()
        end
      end

    [
      quote do
        @typedoc "Union type for all request structs for this API"
        @type request_t :: unquote(Enum.reduce(request_ts, &{:|, [], [&1, &2]}))
      end,
      quote do
        @typedoc "Union type for all response structs for this API"
        @type response_t :: unquote(Enum.reduce(response_ts, &{:|, [], [&1, &2]}))
      end
    ]
  end

  def make_request_getter(vsn) do
    quote do
      def get_request_struct(unquote(vsn)) do
        %unquote(modname(vsn, Request)){}
      end
    end
  end

  def make_response_deserializer(vsn) do
    quote do
      def deserialize(unquote(vsn), data) do
        unquote(modname(vsn, Response)).deserialize(data)
      end
    end
  end

  def make_request_module(api, vsn, schema_module) do
    schema = schema_module.req(api, vsn)

    request_module_name = modname(vsn, Request)
    response_module_name = modname(vsn, Response)

    header_vsn = request_header_version(api, vsn, schema_module)

    struct =
      generate_request_struct(
        api,
        vsn,
        request_module_name,
        response_module_name,
        schema,
        header_vsn
      )

    serializer = generate_serializer(request_module_name)

    List.flatten([struct, serializer])
  end

  def make_response_module(api, vsn, schema_module) do
    schema = schema_module.rsp(api, vsn)

    response_module_name = modname(vsn, Response)
    header_vsn = response_header_version(api, vsn, schema_module)

    struct = generate_response_struct(api, vsn, response_module_name, schema, header_vsn)

    List.flatten([struct])
  end

  defp modname(vsn, suffix) do
    Module.concat(["V#{vsn}", suffix])
  end

  def generate_request_struct(api, vsn, modname, response_modname, schema, header_vsn \\ 1) do
    fields =
      Enum.reduce(schema, [], fn {k, v}, acc ->
        acc ++ [{k, default_val(v)}]
      end) ++ [correlation_id: nil, client_id: nil]

    field_serializers = struct_field_serializers(schema, :struct)

    struct_types =
      Enum.reduce(schema, [], fn {k, v}, acc ->
        acc ++ [{k, describe_type(api, k, v)}]
      end) ++
        [
          correlation_id:
            quote do
              nil | integer()
            end,
          client_id:
            quote do
              nil | binary()
            end
        ]

    # some of the apis don't really have any fields to serialize.  if we don't
    # do this then we end up with an "unused import" warning
    imports =
      if length(fields) > 2 do
        [
          quote do
            import Elixir.Kayrock.Serialize
          end
        ]
      else
        []
      end

    quote do
      defmodule unquote(modname) do
        @vsn unquote(vsn)
        @api unquote(api)
        @schema unquote(schema)
        @moduledoc """
        Kayrock-generated request struct for Kafka `#{@api}` v#{@vsn} API
        messages

        The schema of this API is
        ```
        #{inspect(@schema, pretty: true)}
        ```
        """
        _ = " THIS CODE IS GENERATED BY KAYROCK"
        defstruct unquote(fields)

        unquote_splicing(imports)

        @typedoc """
        Request struct for the Kafka `#{@api}` API v#{@vsn}
        """
        @type t :: %__MODULE__{unquote_splicing(struct_types)}

        @doc "Returns the Kafka API key for this API"
        @spec api_key :: integer
        def api_key, do: Kayrock.KafkaSchemaMetadata.api_key(unquote(api))

        @doc "Returns the API version (#{@vsn}) implemented by this module"
        @spec api_vsn :: integer
        def api_vsn, do: unquote(vsn)

        @doc """
        Returns a function that can be used to deserialize the wire response from the
        broker for this message type
        """
        @spec response_deserializer :: (binary -> {unquote(response_modname).t(), binary})
        def response_deserializer, do: &unquote(response_modname).deserialize/1

        @doc """
        Returns the schema of this message

        See [above](#).
        """
        @spec schema :: term
        def schema, do: unquote(schema)

        @doc "Serialize a message to binary data for transfer to a Kafka broker"
        @spec serialize(t()) :: iodata
        def serialize(%unquote(modname){} = struct) do
          unquote(serialize_request_body(header_vsn, field_serializers))
        end
      end
    end
  end

  # Generates the body of a request serialize/1 function.
  # client_id always uses int16-prefixed nullable_string in ALL header versions
  # (RequestHeader.json: ClientId "flexibleVersions": "none").
  # The only difference between header v1 (non-flexible) and v2 (flexible) is
  # the trailing <<0>> tag_buffer byte.
  # Backwards compatibility: callers used to pass is_flexible (a boolean)
  defp serialize_request_body(true, field_serializers),
    do: serialize_request_body(2, field_serializers)

  defp serialize_request_body(false, field_serializers),
    do: serialize_request_body(1, field_serializers)

  defp serialize_request_body(2, field_serializers) do
    quote do
      [
        <<api_key()::16, api_vsn()::16, struct.correlation_id::32>>,
        case struct.client_id do
          nil -> <<-1::16-signed>>
          id -> <<byte_size(id)::16, id::binary>>
        end,
        <<0>>,
        unquote(field_serializers)
      ]
    end
  end

  defp serialize_request_body(1, field_serializers) do
    quote do
      [
        <<api_key()::16, api_vsn()::16, struct.correlation_id::32>>,
        case struct.client_id do
          nil -> <<-1::16-signed>>
          id -> <<byte_size(id)::16, id::binary>>
        end,
        unquote(field_serializers)
      ]
    end
  end

  def describe_type(:sync_group, :assignment, :bytes) do
    quote do
      nil | Kayrock.MemberAssignment.t()
    end
  end

  def describe_type(_, _, :bytes) do
    quote do
      nil | bitstring()
    end
  end

  def describe_type(_, _, :nullable_string) do
    quote do
      nil | binary()
    end
  end

  def describe_type(_, _, :string) do
    quote do
      nil | binary()
    end
  end

  def describe_type(_, _, :records) do
    quote do
      nil | Kayrock.MessageSet.t() | Kayrock.RecordBatch.t()
    end
  end

  def describe_type(api, field, mapspec) when is_list(mapspec) do
    field_types =
      Enum.map(mapspec, fn {k, v} ->
        {k, describe_type(api, {field, k}, v)}
      end)

    quote do
      %{unquote_splicing(field_types)}
    end
  end

  def describe_type(api, field, {:array, arrayspec}) do
    inner_type = describe_type(api, field, arrayspec)

    quote do
      [unquote(inner_type)]
    end
  end

  def describe_type(_, _, t) when t in [:boolean, :int8, :int16, :int32, :int64] do
    quote do
      nil | integer()
    end
  end

  def describe_type(_, _, :uint16) do
    quote do
      nil | non_neg_integer()
    end
  end

  # NaN / +-Infinity are carried as their raw 8-byte IEEE 754 encoding
  def describe_type(_, _, :float64) do
    quote do
      nil | float() | <<_::64>>
    end
  end

  # 16 raw bytes; nil serializes as the zero UUID
  def describe_type(_, _, :uuid) do
    quote do
      nil | <<_::128>>
    end
  end

  def describe_type(_, _, :compact_records) do
    quote do
      nil | Kayrock.MessageSet.t() | Kayrock.RecordBatch.t()
    end
  end

  def describe_type(api, field, {:nullable_struct, schema}) when is_list(schema) do
    inner = describe_type(api, field, schema)

    quote do
      nil | unquote(inner)
    end
  end

  def describe_type(_, _, t) when t in Kayrock.Serialize.compact_primitive_types() do
    quote do
      nil | binary()
    end
  end

  def describe_type(api, field, {:tagged_field, opts}) when is_list(opts) do
    describe_type(api, field, Keyword.fetch!(opts, :type))
  end

  def describe_type(_, _, :tagged_fields) do
    quote do
      [{non_neg_integer(), binary()}]
    end
  end

  def describe_type(api, field, {:compact_array, type}) when is_atom(type) do
    inner = describe_type(api, field, type)

    quote do
      nil | [unquote(inner)]
    end
  end

  def describe_type(api, field, {:compact_array, schema}) when is_list(schema) do
    field_types = Enum.map(schema, fn {k, v} -> {k, describe_type(api, {field, k}, v)} end)

    quote do
      nil | [%{unquote_splicing(field_types)}]
    end
  end

  def describe_type(_, _, t) do
    IO.puts("Unhandled type: #{inspect(t)} will be spec'ed as term()")

    quote do
      term()
    end
  end

  def generate_response_struct(api, vsn, modname, schema, header_vsn \\ 0) do
    fields =
      Enum.reduce(schema, [], fn {k, v}, acc ->
        acc ++ [{k, default_val(v)}]
      end) ++ [correlation_id: nil]

    struct_types =
      Enum.reduce(schema, [], fn {k, v}, acc ->
        acc ++ [{k, describe_type(api, k, v)}]
      end) ++
        [
          correlation_id:
            quote do
              integer()
            end
        ]

    {first_field_name, field_deserializers} = struct_field_deserializers(:root, schema)
    field_deserializers = List.flatten(field_deserializers)

    quote do
      defmodule unquote(modname) do
        @vsn unquote(vsn)
        @api unquote(api)
        @schema unquote(schema)
        @moduledoc """
        Kayrock-generated response struct for Kafka `#{@api}` v#{@vsn} API
        messages

        The schema of this API is
        ```
        #{inspect(@schema, pretty: true)}
        ```
        """
        _ = " THIS CODE IS GENERATED BY KAYROCK"
        defstruct unquote(fields)

        @typedoc """
        Response struct for the Kafka `#{@api}` API v#{@vsn}
        """
        @type t :: %__MODULE__{unquote_splicing(struct_types)}

        import Elixir.Kayrock.Deserialize

        @doc "Returns the Kafka API key for this API"
        @spec api_key :: integer
        def api_key, do: Kayrock.KafkaSchemaMetadata.api_key(unquote(api))

        @doc "Returns the API version (#{@vsn}) implemented by this module"
        @spec api_vsn :: integer
        def api_vsn, do: unquote(vsn)

        @doc """
        Returns the schema of this message

        See [above](#).
        """
        @spec schema :: term
        def schema, do: unquote(schema)

        @doc """
        Deserialize data for this version of this API
        """
        @spec deserialize(binary) :: {t(), binary}
        def deserialize(data) do
          unquote(
            # Note: ApiVersionsResponse ALWAYS uses response header v0 (KIP-511),
            # even for V3+ which is technically a flexible version.  This lets
            # old clients that don't understand flexible headers still
            # negotiate versions.  See response_header_version/3.
            case header_vsn do
              # (`true`/`false` accepted for backwards compatibility with the
              # former is_flexible argument; `true` meant header v1 except for
              # ApiVersions)
              v when v == 1 or (v == true and api != :api_versions) ->
                # Flexible version response header (KIP-482): correlation_id + TAG_BUFFER
                quote do
                  <<correlation_id::32-signed, rest::binary>> = data
                  # Read and discard the tagged fields from the response header
                  {_tagged_fields, rest} = deserialize_tagged_fields(rest)

                  deserialize_field(
                    :root,
                    unquote(first_field_name),
                    %__MODULE__{correlation_id: correlation_id},
                    rest
                  )
                end

              v when v in [0, false, true] ->
                # Standard (non-flexible) response header: just correlation_id
                quote do
                  <<correlation_id::32-signed, rest::binary>> = data

                  deserialize_field(
                    :root,
                    unquote(first_field_name),
                    %__MODULE__{correlation_id: correlation_id},
                    rest
                  )
                end
            end
          )
        end

        unquote_splicing(field_deserializers)

        defp deserialize_field(_, nil, acc, rest) do
          {acc, rest}
        end
      end
    end
  end

  # we need 'next field' to build the recursive deserializer
  # we also tack on a nil to signify the final field
  defp build_field_zip(schema) do
    field_names = Keyword.keys(schema)
    [first_field_name | rest_of_fields] = field_names
    fields_with_next_field = Enum.zip(schema, rest_of_fields ++ [nil])
    {first_field_name, fields_with_next_field}
  end

  ######################################################################
  # NAMED TAGGED FIELDS (KIP-482)
  #
  # JSON-derived schemas describe a tagged field as
  # `{name, {:tagged_field, [tag: tag, type: type, default: default]}}`
  # (see Kayrock.Generate.JsonSpec).  Such fields are struct keys like any
  # other, but on the wire they live in the struct's tagged-field section
  # (`{:tagged_fields, :tagged_fields}`), not inline.  Structs without named
  # tagged fields generate exactly the same code as before.

  @doc false
  def tagged_field?({_name, {:tagged_field, opts}}) when is_list(opts), do: true
  def tagged_field?(_), do: false

  defp named_tagged_fields(schema), do: Enum.filter(schema, &tagged_field?/1)

  # serializers for every field of a struct, read from `varname`
  defp struct_field_serializers(schema, varname) do
    case named_tagged_fields(schema) do
      [] ->
        Enum.map(schema, &field_serializer(&1, varname))

      tagged ->
        schema
        |> Enum.reject(&tagged_field?/1)
        |> Enum.map(fn
          {:tagged_fields, :tagged_fields} -> tagged_section_serializer(tagged, varname)
          field -> field_serializer(field, varname)
        end)
    end
  end

  defp tagged_section_serializer(tagged, varname) do
    var = Macro.var(varname, __MODULE__)

    named =
      Enum.map(tagged, fn {name, {:tagged_field, opts}} ->
        tag = Keyword.fetch!(opts, :tag)
        type = Keyword.fetch!(opts, :type)

        kind = value_kind(type, opts)

        quote do
          with {:ok, value} <- Map.fetch(unquote(var), unquote(name)),
               false <-
                 Kayrock.Serialize.tagged_field_default?(
                   unquote(kind),
                   value,
                   unquote(Keyword.fetch!(opts, :default))
                 ) do
            {unquote(tag),
             IO.iodata_to_binary(unquote(tagged_value_serializer(name, type, kind)))}
          else
            _ -> nil
          end
        end
      end)

    quote do
      Kayrock.Serialize.serialize_tagged_fields(
        unquote(named),
        Map.get(unquote(var), :tagged_fields, [])
      )
    end
  end

  # serializes `value` (bound by tagged_section_serializer/2) as `type`
  defp tagged_value_serializer(_name, :boolean, :boolean) do
    quote do
      Kayrock.Serialize.serialize(:boolean, Kayrock.Serialize.tagged_field_value(:boolean, value))
    end
  end

  defp tagged_value_serializer(name, type, _kind) do
    quote do
      tagged_value = %{unquote(name) => value}
      unquote(field_serializer({name, type}, :tagged_value))
    end
  end

  # how Kayrock.Serialize.tagged_field_default?/3 compares a value to the default
  defp value_kind(type, opts) do
    cond do
      Keyword.get(opts, :nullable, false) -> :nullable
      type == :boolean -> :boolean
      true -> :value
    end
  end

  # deserializers for every field of a struct in `scope`; returns the name of
  # the first inline field and the deserializer clauses
  defp struct_field_deserializers(scope, schema) do
    tagged = named_tagged_fields(schema)

    {first_field_name, fields_with_next_field} =
      build_field_zip(Enum.reject(schema, &tagged_field?/1))

    deserializers =
      Enum.map(fields_with_next_field, fn
        {{:tagged_fields, :tagged_fields}, next} when tagged != [] ->
          tagged_section_deserializer(scope, tagged, next)

        {field, next} ->
          generate_field_deserializer(scope, field, next)
      end)

    {first_field_name, deserializers}
  end

  # Decodes the tagged-field section: known tags are decoded into their named
  # fields (absent ones take their default), unknown tags are kept as raw
  # `{tag, binary}` pairs in `:tagged_fields`.
  defp tagged_section_deserializer(scope, tagged, next_field_name) do
    value_scope = {:tagged, scope}

    value_deserializers =
      Enum.map(tagged, fn {name, {:tagged_field, opts}} ->
        generate_field_deserializer(value_scope, {name, Keyword.fetch!(opts, :type)}, nil)
      end)

    defaults =
      Enum.map(tagged, fn {name, {:tagged_field, opts}} ->
        {name, Keyword.fetch!(opts, :default)}
      end)

    decode_clauses =
      Enum.flat_map(tagged, fn {name, {:tagged_field, opts}} ->
        quote do
          unquote(Keyword.fetch!(opts, :tag)) ->
            {decoded, _} = deserialize_field(unquote(value_scope), unquote(name), %{}, bin)
            {Map.put(acc, unquote(name), Map.fetch!(decoded, unquote(name))), unknown}
        end
      end) ++
        quote do
          _ -> {acc, [{tag, bin} | unknown]}
        end

    [
      value_deserializers,
      quote do
        defp deserialize_field(unquote(scope), :tagged_fields, acc, data) do
          {raw, rest} = Kayrock.Deserialize.deserialize_tagged_fields(data)

          {acc, unknown} =
            raw
            |> Enum.sort_by(&elem(&1, 0))
            |> Enum.reduce(
              {Map.merge(acc, %{unquote_splicing(defaults)}), []},
              fn {tag, bin}, {acc, unknown} ->
                case tag do
                  unquote(decode_clauses)
                end
              end
            )

          deserialize_field(
            unquote(scope),
            unquote(next_field_name),
            Map.put(acc, :tagged_fields, Enum.reverse(unknown)),
            rest
          )
        end
      end
    ]
  end

  def generate_field_deserializer(scope, {:assignment, :compact_bytes}, next_field_name) do
    quote do
      defp deserialize_field(unquote(scope), :assignment, acc, data) do
        {raw, rest} = Kayrock.Deserialize.deserialize(:compact_bytes, data)
        val = Kayrock.MemberAssignment.deserialize_content(raw)

        deserialize_field(
          unquote(scope),
          unquote(next_field_name),
